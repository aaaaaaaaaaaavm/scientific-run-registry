from __future__ import annotations
import argparse
import binascii
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import struct
import subprocess
import sys
import tempfile
from urllib.parse import unquote
import zipfile

ROOT = Path(__file__).resolve().parents[1]
LIMIT = 30_000_000
TEXT = {'.md','.txt','.tex','.html','.htm','.py','.js','.cjs','.json','.yml','.yaml','.csv','.sh','.svg','.scad','.css','.cff','.toml'}
SECRET = [
 (re.compile(rb'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----'), 'private key'),
 (re.compile(rb'\bgh[pousr]_[A-Za-z0-9_]{25,}\b|\bgithub_pat_[A-Za-z0-9_]{25,}\b'), 'GitHub token'),
 (re.compile(rb'\bAKIA[0-9A-Z]{16}\b'), 'AWS access key'),
 (re.compile(rb'Message Type:\s+(?:NEW_TASK|FINAL_ANSWER)\b'), 'conversation export'),
 (re.compile(rb'/workspace[/]volley-work[/]'), 'private workspace path'),
]
PRIVATE_NAMES = ('GUIDE_DECISION_REQUEST','INTERNAL_HANDOFF','PRIVATE_REVIEW_DRAFT','CLOUD_HANDOFF_RULES','VISUAL_UI_UX_SCOPE')
LINK = re.compile(r"!?\[[^\]]*\]\((<[^>]+>|[^)]+)\)|<img\b[^>]*\bsrc=['\"]([^'\"]+)",re.I)

def git(*args: str, env: dict | None = None) -> bytes:
 return subprocess.check_output(['git',*args],cwd=ROOT,env=env,stderr=subprocess.PIPE)

def privacy(name: str, data: bytes, errors: list[str]) -> None:
 base=PurePosixPath(name).name
 if any(word in name.upper() for word in PRIVATE_NAMES) or base in {'.env','id_rsa','id_ed25519'} or name.lower().endswith('.fcbak'):
  errors.append(f'{name}: private draft, credential file or uncontrolled CAD backup')
 for pattern,label in SECRET:
  if pattern.search(data): errors.append(f'{name}: possible {label}')

def links(root: Path, path: Path, text: str, errors: list[str]) -> None:
 # Immutable source fixtures retain their original link context; their exact bytes
 # are checked by verify_repository.py. Current authored pages are all checked.
 if path.relative_to(root).as_posix().startswith('reference/volley/'): return
 fenced=False
 for number,line in enumerate(text.splitlines(),1):
  if line.lstrip().startswith(('```','~~~')): fenced=not fenced;continue
  if fenced:continue
  for match in LINK.finditer(line):
   raw=next(g for g in match.groups() if g).strip('<>')
   target=unquote(raw.split('#',1)[0].split('?',1)[0])
   if not target or target.startswith(('http:','https:','mailto:','data:','//','#')):continue
   if any(mark in target for mark in ('{','}','$','*','<','>')):continue
   resolved=(path.parent/target).resolve()
   if not resolved.is_relative_to(root) or not resolved.exists():errors.append(f'{path.relative_to(root)}:{number}: local link does not resolve inside payload')

def png_valid(data: bytes) -> bool:
 if not data.startswith(b'\x89PNG\r\n\x1a\n'):return False
 pos=8;first=True
 while pos+12<=len(data):
  size=struct.unpack('>I',data[pos:pos+4])[0];kind=data[pos+4:pos+8];end=pos+12+size
  if end>len(data):return False
  if first and (kind!=b'IHDR' or size!=13):return False
  if binascii.crc32(data[pos+4:end-4]) & 0xffffffff != struct.unpack('>I',data[end-4:end])[0]:return False
  first=False;pos=end
  if kind==b'IEND':return size==0 and pos==len(data)
 return False

def check_file(root: Path, path: Path, errors: list[str]) -> None:
 rel=path.relative_to(root).as_posix()
 if path.stat().st_size>LIMIT:errors.append(f'{rel}: exceeds 30 MB');return
 data=path.read_bytes();privacy(rel,data,errors);suffix=path.suffix.lower()
 if suffix in TEXT:
  try:value=data.decode('utf-8')
  except UnicodeDecodeError:errors.append(f'{rel}: expected UTF-8 text');return
  footer = r"(?im)^[\s>*]*(?:<!--\s*)?generated by\s+(?!(?:`|[\w./-]+\.py\b|Gmsh\b|Matplotlib\b|FreeCAD\b|CadQuery\b|OpenSCAD\b|Blender\b|CalculiX\b|Pandoc\b|ReportLab\b|XeLaTeX\b|LaTeX\b))[\w-]+"
  if re.search(footer,value):errors.append(f'{rel}: generation footer requires identifiable source provenance')
  if suffix=='.md':links(root,path,value,errors)
  if suffix=='.json':
   try:json.loads(value,parse_constant=lambda v:(_ for _ in ()).throw(ValueError(v)))
   except (ValueError,TypeError):errors.append(f'{rel}: invalid or non-finite JSON')
 elif suffix=='.pdf' and (not data.startswith(b'%PDF-') or b'%%EOF' not in data[-2048:]):errors.append(f'{rel}: incomplete PDF')
 elif suffix in {'.step','.stp'} and (not data.lstrip().startswith(b'ISO-10303-21;') or b'END-ISO-10303-21;' not in data[-1024:]):errors.append(f'{rel}: incomplete STEP exchange')
 elif suffix=='.png' and not png_valid(data):errors.append(f'{rel}: invalid PNG chunks/signature')
 elif suffix in {'.jpg','.jpeg'} and (not data.startswith(b'\xff\xd8\xff') or b'\xff\xd9' not in data[-32:]):errors.append(f'{rel}: incomplete JPEG')
 if suffix in {'.zip','.docx','.pptx','.xlsx','.fcstd'}:
  try:
   with zipfile.ZipFile(path) as archive:
    members=archive.infolist()
    if sum(m.file_size for m in members)>256_000_000:raise ValueError('expanded container exceeds bounded inspection limit')
    required={'.docx':'word/document.xml','.pptx':'ppt/presentation.xml','.xlsx':'xl/workbook.xml','.fcstd':'Document.xml'}.get(suffix)
    if required and required not in archive.namelist():raise ValueError('missing native document member')
    for member in members:
     item=PurePosixPath(member.filename)
     if item.is_absolute() or '..' in item.parts or '\\' in member.filename:raise ValueError('unsafe member path')
     if member.file_size>LIMIT:raise ValueError('container member exceeds 30 MB')
     privacy(rel+'!'+member.filename,archive.read(member),errors)
  except (ValueError,zipfile.BadZipFile,RuntimeError,OSError) as exc:errors.append(f'{rel}: invalid container ({exc})')

def run_check(snapshot: Path, argv: list[str], env: dict) -> dict:
 result=subprocess.run([sys.executable,*argv],cwd=snapshot,env=env,capture_output=True,text=True)
 output=result.stdout+result.stderr
 if result.returncode:raise ValueError(f'{argv[0]} failed:\n{output[-5000:]}')
 match=re.search(r'Ran (\d+) tests?',output)
 return {'command':[sys.executable,*argv],'passed':True,'tests':int(match.group(1)) if match else None,'summary':output.strip().splitlines()[-1] if output.strip() else 'PASS'}

def main() -> int:
 parser=argparse.ArgumentParser(description=__doc__)
 parser.add_argument('--all',action='store_true',help='check the entire selected index; default behavior')
 parser.add_argument('--commit',help='check this exact commit tree, without changing the working index')
 parser.add_argument('--receipt',type=Path,help='write a local JSON verification receipt')
 args=parser.parse_args();errors=[]
 try:
  with tempfile.TemporaryDirectory(prefix='support-prepublish-') as temp:
   temporary=Path(temp);env=os.environ.copy()
   if args.commit:
    if args.commit.startswith('-'):raise ValueError('invalid commit argument')
    commit=git('rev-parse','--verify',args.commit+'^{commit}').decode().strip()
    env['GIT_INDEX_FILE']=str(temporary/'index')
    git('read-tree',commit,env=env)
   rows=git('ls-files','--stage','-z',env=env).split(b'\0');paths=[]
   for row in filter(None,rows):
    header,name=row.split(b'\t',1);mode,blob,stage=header.decode().split();relative=name.decode('utf-8')
    parts=PurePosixPath(relative)
    if mode not in {'100644','100755'} or stage!='0':raise ValueError('unmerged, symbolic-link or submodule payload needs explicit review')
    if parts.is_absolute() or '..' in parts.parts or '\n' in relative:raise ValueError('unsafe indexed path')
    paths.append(relative)
   if not paths:raise ValueError('empty publication index')
   tree=git('write-tree',env=env).decode().strip()
   snapshot=temporary/'payload';snapshot.mkdir()
   git('checkout-index','--all','--prefix='+str(snapshot)+'/',env=env)
   if (snapshot/'tools/prepublish_gate.py').read_bytes()!=Path(__file__).read_bytes():raise ValueError('gate source differs from selected payload; stage or check out the intended gate')
   for relative in paths:check_file(snapshot,snapshot/relative,errors)
   if errors:raise ValueError('\n'.join(errors))
   child_env=os.environ.copy()
   for key in ('GIT_INDEX_FILE','GIT_DIR','GIT_WORK_TREE'):child_env.pop(key,None)
   child_env['PYTHONPATH']=str(snapshot/'src');child_env['PYTHONDONTWRITEBYTECODE']='1'
   checks=[run_check(snapshot,['-m','unittest','discover','-s','tests','-v'],child_env)]
   for validator in ['tools/verify_repository.py','tools/check_scientific_assets.py']:
    if (snapshot/validator).is_file():checks.append(run_check(snapshot,[validator],child_env))
   receipt={'scope':'Exact Git tree; offline file/privacy/container/link checks and local tests','tree':tree,'indexed_paths':len(paths),'checks':checks,'passed':True,'human_review_performed':False}
   if args.receipt:args.receipt.write_text(json.dumps(receipt,indent=2)+'\n')
   print(f'PASS: exact tree {tree}; {len(paths)} indexed paths; {checks[0]["tests"]} tests; {len(checks)-1} fixture/figure validators')
   return 0
 except (ValueError,OSError,subprocess.CalledProcessError,UnicodeError) as exc:
  print(f'FAIL: publication gate: {exc}',file=sys.stderr);return 1
if __name__=='__main__':raise SystemExit(main())
